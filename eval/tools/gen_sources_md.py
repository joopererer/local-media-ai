"""从 eval/public/manifest.jsonl 生成 eval/public/SOURCES.md。

manifest.jsonl 是机器可读的来源清单（每行一个文件），SOURCES.md 是它的人类可读版本。
两者必须一致：改了 manifest 就重跑这个脚本。

用法：python eval/tools/gen_sources_md.py
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "eval" / "public" / "manifest.jsonl"
OUT = ROOT / "eval" / "public" / "SOURCES.md"

LICENSE_LABEL = {
    "cc0": "CC0 1.0 (public domain dedication)",
    "pd": "Public domain",
    "cc-by": "CC BY",
    "cc-by-sa": "CC BY-SA",
}


def main() -> int:
    if not MANIFEST.exists():
        print(f"missing {MANIFEST}", file=sys.stderr)
        return 1

    rows = []
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line:
            rows.append(json.loads(line))
    if not rows:
        print("manifest is empty", file=sys.stderr)
        return 1

    unknown = [r for r in rows if r.get("license_id") not in ("cc0", "pd")]
    if unknown:
        names = ", ".join(r.get("file", "?") for r in unknown)
        print(
            f"refusing to generate: {len(unknown)} file(s) are not CC0/public domain: {names}",
            file=sys.stderr,
        )
        return 2

    lines = [
        "# Public evaluation images — source, author and licence",
        "",
        "Every image in `eval/public/images/` is **CC0 1.0** or **public domain**.",
        "Files whose licence could not be confirmed are excluded from this repository",
        "entirely (they stay in the private evaluation set).",
        "",
        "This file is generated from `eval/public/manifest.jsonl` —",
        "run `python eval/tools/gen_sources_md.py` after changing the manifest.",
        "",
        "| file | topic | licence | author | source |",
        "|---|---|---|---|---|",
    ]
    for r in sorted(rows, key=lambda x: x.get("file", "")):
        label = LICENSE_LABEL.get(r.get("license_id", ""), r.get("license", ""))
        author = (r.get("author") or "—").replace("|", "\\|")
        page = r.get("page_url") or "—"
        lines.append(
            f"| `{r.get('file','')}` | {r.get('topic','')} | {label} | {author} | {page} |"
        )

    lines += [
        "",
        "## Licences",
        "",
        "- **CC0 1.0** — <https://creativecommons.org/publicdomain/zero/1.0/>",
        "- **Public domain** — the work is not covered by copyright.",
        "",
        "## OCR fixtures",
        "",
        "The images under `eval/public/ocr/` are generated by",
        "`eval/tools/gen_ocr_fixtures.py` — they contain no third-party material.",
        "",
    ]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} images)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
